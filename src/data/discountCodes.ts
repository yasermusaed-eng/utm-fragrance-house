export function validatePromoCode(inputCode: string): { isValid: boolean; discount?: DiscountCode; message: string } {
  const normalized = inputCode.trim().toUpperCase();
  if (!normalized) {
    return { isValid: false, message: 'Please enter a voucher code.' };
  }

  const discount = SURVEY_DISCOUNT_CODES[normalized];
  if (!discount) {
    return { isValid: false, message: 'Invalid voucher code. Please check your email.' };
  }

  // Check if already used in localStorage
  try {
    const usedRaw = localStorage.getItem('utm_used_discount_codes');
    const usedCodes: Record<string, string> = usedRaw ? JSON.parse(usedRaw) : {};
    if (usedCodes[normalized]) {
      return {
        isValid: false,
        message: `This one-time voucher (${normalized}) was already redeemed on ${usedCodes[normalized]}.`
      };
    }
  } catch (e) {
    console.error('Error checking used discount codes', e);
  }

  return {
    isValid: true,
    discount,
    message: `VIP 20% Survey Reward Applied! (-${discount.discountPercent}%)`
  };
}

export function markCodeAsUsed(code: string, orderId: string) {
  const normalized = code.trim().toUpperCase();
  try {
    const usedRaw = localStorage.getItem('utm_used_discount_codes');
    const usedCodes: Record<string, string> = usedRaw ? JSON.parse(usedRaw) : {};
    usedCodes[normalized] = new Date().toLocaleDateString() + ' (Order #' + orderId + ')';
    localStorage.setItem('utm_used_discount_codes', JSON.stringify(usedCodes));
  } catch (e) {
    console.error('Error marking discount code as used', e);
  }
}

export function getUsedCodesMap(): Record<string, string> {
  try {
    const usedRaw = localStorage.getItem('utm_used_discount_codes');
    return usedRaw ? JSON.parse(usedRaw) : {};
  } catch {
    return {};
  }
}
